#!/usr/bin/env node
/**
 * migrate-kv-to-d1.js
 *
 * One-off migration from the old v7 (KV-only) data layout to the new
 * v7-d1 layout (D1 for everything except sessions, which stay in KV).
 *
 * WHAT IT DOES
 *   1. Uses `wrangler kv key list` + `wrangler kv key get` to pull every
 *      topic:*, submission:*, pupil:*, and teacheradmin:* entry out of your
 *      EXISTING KV namespace (the one your old v7 deployment used).
 *   2. Also copies over config:teacher_password, config:rubric and
 *      config:model_groq into the new D1 config table.
 *   3. Writes a single migration.sql file with INSERT statements matching
 *      schema.sql.
 *   4. Does NOT touch your live KV namespace or run anything remotely by
 *      itself - it only reads via wrangler and writes a local .sql file.
 *      You apply that file yourself (step 3 below), so you can look it over
 *      first if you want.
 *
 * BEFORE YOU RUN THIS
 *   - Deploy the new v7-d1 code and run schema.sql against your D1 database
 *     FIRST (see README "Upgrading from KV-only v7"), so the tables this
 *     script inserts into already exist.
 *   - Make sure `wrangler` is installed and logged in (`wrangler login`),
 *     and that you know your OLD KV binding name (this script assumes it's
 *     still CCv6_DATA, same as before - if you renamed it, edit KV_BINDING
 *     below) and your NEW D1 database name (edit D1_DB_NAME below).
 *   - Run this from Cloud Shell, a local terminal, or anywhere with Node.js
 *     and the wrangler CLI available - it shells out to `wrangler`, it does
 *     not call the Cloudflare API directly.
 *
 * HOW TO RUN IT
 *   node migrate-kv-to-d1.js
 *     -> writes migration.sql in the current directory
 *
 *   wrangler d1 execute chitchat-v7 --remote --file=migration.sql
 *     -> actually applies it to your live D1 database
 *
 *   (swap --remote for nothing / for a local dev database if you want to
 *   test against local D1 first)
 *
 * This script is idempotent-ish: topics/pupils/teacher_admins use
 * "INSERT OR IGNORE", so re-running it after a partial apply won't create
 * duplicates for those tables. submissions and pupil_history use plain
 * INSERT (their ids/rows aren't naturally re-derivable the same way) - if
 * you need to re-run after those already landed, wipe the migration.sql
 * output and re-apply schema.sql to a fresh D1 database rather than running
 * this twice against the same one.
 */

const { execFileSync } = require("child_process");
const fs = require("fs");

const KV_BINDING = "CCv6_DATA"; // your OLD KV namespace binding (pre-migration)
const REMOTE = true; // set false to read from a local dev KV namespace instead

function sh(args) {
  const flags = REMOTE ? ["--remote"] : [];
  return execFileSync("wrangler", [...args, ...flags], { encoding: "utf8", maxBuffer: 1024 * 1024 * 64 });
}

function kvListKeys(prefix) {
  const out = sh(["kv", "key", "list", `--binding=${KV_BINDING}`, `--prefix=${prefix}`]);
  return JSON.parse(out).map((k) => k.name);
}

function kvGet(key) {
  return sh(["kv", "key", "get", `--binding=${KV_BINDING}`, key]);
}

// Minimal SQL string literal escaping - doubles single quotes. Every value
// goes through this; there is no string concatenation of untrusted data
// anywhere else in the generated SQL.
function sqlStr(v) {
  if (v === null || v === undefined) return "NULL";
  return "'" + String(v).replace(/'/g, "''") + "'";
}
function sqlNum(v) {
  const n = Number(v);
  return Number.isFinite(n) ? String(n) : "0";
}
function sqlBool(v) {
  return v ? "1" : "0";
}
function sqlJson(v) {
  return sqlStr(JSON.stringify(v === undefined ? null : v));
}

function main() {
  const lines = [];
  lines.push("-- Generated by migrate-kv-to-d1.js - review before applying.");
  lines.push("BEGIN TRANSACTION;");

  // ---- topics ----
  console.error("Reading topics...");
  const topicKeys = kvListKeys("topic:").filter((k) => k !== "topics_index");
  for (const key of topicKeys) {
    const t = JSON.parse(kvGet(key));
    lines.push(
      `INSERT OR IGNORE INTO topics (id, title, image_url, image_description, questions, tags, coach, created_at) VALUES ` +
        `(${sqlStr(t.id)}, ${sqlStr(t.title || "Untitled topic")}, ${sqlStr(t.imageUrl || "")}, ${sqlStr(t.imageDescription || "")}, ` +
        `${sqlJson(t.questions || [])}, ${sqlJson(t.tags || [])}, ${sqlJson(t.coach || [])}, ${Date.now()});`
    );
  }
  console.error(`  ${topicKeys.length} topics.`);

  // ---- pupils + pupil history ----
  // We need pupils inserted (and their new auto-increment ids known) BEFORE
  // history rows can reference them, so this uses a subquery per history row
  // rather than trying to track ids client-side.
  console.error("Reading pupils...");
  const pupilKeys = kvListKeys("pupil:").filter((k) => !k.endsWith(":history"));
  for (const key of pupilKeys) {
    const p = JSON.parse(kvGet(key));
    lines.push(
      `INSERT OR IGNORE INTO pupils (name, pupil_class, best_score, total_score, attempts) VALUES ` +
        `(${sqlStr(p.name)}, ${sqlStr(p.pupilClass || "unassigned")}, ${sqlNum(p.bestScore)}, ${sqlNum(p.totalScore)}, ${sqlNum(p.attempts)});`
    );
  }
  console.error(`  ${pupilKeys.length} pupils.`);

  console.error("Reading pupil history...");
  const historyKeys = kvListKeys("pupil:").filter((k) => k.endsWith(":history"));
  let historyRows = 0;
  for (const key of historyKeys) {
    // key looks like pupil:<class>:<name>:history - recover class/name the
    // same way the old pupilKey()/pupilHistoryKey() built it (colon-joined,
    // sanitized segments), by stripping the pupil: prefix and :history suffix.
    const middle = key.replace(/^pupil:/, "").replace(/:history$/, "");
    const parts = middle.split(":");
    const pupilClass = parts.shift();
    const name = parts.join(":"); // in case the name itself had a stray colon stripped inconsistently, join the rest back
    const history = JSON.parse(kvGet(key));
    for (const h of history) {
      const pupilIdSubquery = `(SELECT id FROM pupils WHERE name = ${sqlStr(name)} AND pupil_class = ${sqlStr(pupilClass)})`;
      lines.push(
        `INSERT INTO pupil_history (pupil_id, timestamp, topic_id, topic_title, final_score, max_score, breakdown) VALUES ` +
          `(${pupilIdSubquery}, ${sqlNum(h.timestamp)}, ${sqlStr(h.topicId)}, ${sqlStr(h.topicTitle)}, ${sqlNum(h.finalScore)}, ${sqlNum(h.maxScore)}, ${sqlJson(h.breakdown || [])});`
      );
      historyRows++;
    }
  }
  console.error(`  ${historyRows} history rows across ${historyKeys.length} pupils.`);

  // ---- submissions ----
  console.error("Reading submissions...");
  const subKeys = kvListKeys("submission:");
  for (const key of subKeys) {
    const s = JSON.parse(kvGet(key));
    lines.push(
      `INSERT INTO submissions (id, pupil_name, pupil_class, topic_id, topic_title, mode, rounds, final_score, max_score, practice, grading_degraded, repeated_ideas_penalty, archived, flagged, created_at) VALUES ` +
        `(${sqlStr(s.id)}, ${sqlStr(s.pupilName)}, ${sqlStr(s.pupilClass || "unassigned")}, ${sqlStr(s.topicId)}, ${sqlStr(s.topicTitle)}, ${sqlStr(s.mode)}, ` +
        `${sqlJson(s.rounds || [])}, ${sqlNum(s.finalScore)}, ${sqlNum(s.maxScore)}, ${sqlBool(s.practice)}, ${sqlBool(s.gradingDegraded)}, ${sqlBool(s.repeatedIdeasPenalty)}, ${sqlBool(s.archived)}, ${sqlBool(s.flagged)}, ${sqlNum(s.createdAt)});`
    );
  }
  console.error(`  ${subKeys.length} submissions.`);

  // ---- teacher-admin accounts ----
  console.error("Reading teacher-admin accounts...");
  const taKeys = kvListKeys("teacheradmin:");
  for (const key of taKeys) {
    const r = JSON.parse(kvGet(key));
    lines.push(
      `INSERT OR IGNORE INTO teacher_admins (username, salt, hash, classes, created_at) VALUES ` +
        `(${sqlStr(r.username)}, ${sqlStr(r.salt)}, ${sqlStr(r.hash)}, ${sqlJson(r.classes || [])}, ${sqlNum(r.createdAt || Date.now())});`
    );
  }
  console.error(`  ${taKeys.length} teacher-admin accounts.`);

  // ---- settings ----
  console.error("Reading settings (teacher password / rubric / groq model)...");
  for (const [kvKey, configKey] of [
    ["config:teacher_password", "teacher_password"],
    ["config:rubric", "rubric"],
    ["config:model_groq", "model_groq"],
  ]) {
    let val;
    try {
      val = sh(["kv", "key", "get", `--binding=${KV_BINDING}`, kvKey]);
    } catch (e) {
      val = null; // key didn't exist - fine, that setting was just using its default
    }
    if (val) {
      lines.push(`INSERT OR REPLACE INTO config (key, value) VALUES (${sqlStr(configKey)}, ${sqlStr(val.trim())});`);
    }
  }

  lines.push("COMMIT;");
  fs.writeFileSync("migration.sql", lines.join("\n") + "\n");
  console.error(`\nWrote migration.sql (${lines.length} lines).`);
  console.error("Review it, then apply with:");
  console.error("  wrangler d1 execute chitchat-v7 --remote --file=migration.sql");
}

main();
